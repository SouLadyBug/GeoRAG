"""Open water at Lake Ichkeul, Tunisia: 2020-02 vs 2025-02

Generated by GeoRAG from the plan below. Method: monthly median MNDWI composites from
Sentinel-2 L2A, clouds and shadows removed with the scene classification layer (SCL), water where
MNDWI > 0.0.

Plan: {"task": "water_change", "place": "Lake Ichkeul, Tunisia", "bbox": [9.55, 37.1, 9.775, 37.215], "periods": ["2020-02", "2025-02"], "index": "MNDWI", "threshold": 0.0, "max_cloud": 30.0, "max_scenes": 4, "resolution": 20}
"""

import json

import numpy as np

from georag.geo import eo

BBOX = (9.55, 37.1, 9.775, 37.215)  # lon_min, lat_min, lon_max, lat_max (Lake Ichkeul, Tunisia)
PERIODS = ['2020-02', '2025-02']
INDEX = "MNDWI"
THRESHOLD = 0.0
MAX_CLOUD = 30.0
MAX_SCENES = 4
RESOLUTION = 20

composites, masks, stats = [], [], []
for month in PERIODS:
    comp = eo.monthly_composite(BBOX, month, INDEX, MAX_CLOUD, MAX_SCENES, RESOLUTION)
    mask, s = eo.water_stats(comp, THRESHOLD)
    eo.write_geotiff(f"{INDEX.lower()}_{month}.tif", comp.index, comp.grid, nodata=float("nan"))
    eo.write_geotiff(f"water_{month}.tif", mask.astype("uint8"), comp.grid)
    composites.append(comp)
    masks.append(mask)
    stats.append(s)
    print(f"{month}: {s['water_km2']:.2f} km2 of water from {len(comp.scenes)} scenes")

# Compare only pixels observed in both months, so cloud gaps are not counted as change.
both = np.isfinite(composites[0].index) & np.isfinite(composites[1].index)
a, b = masks[0] & both, masks[1] & both
change = np.zeros(a.shape, np.int8)
change[a & b] = 2
change[~a & b] = 1
change[a & ~b] = -1
px_km2 = composites[0].grid.pixel_area_m2 / 1e6
area_a, area_b = a.sum() * px_km2, b.sum() * px_km2
result = {
    "place": "Lake Ichkeul, Tunisia",
    "bbox": BBOX,
    "periods": stats,
    "comparable_fraction": round(float(both.mean()), 4),
    "water_km2_a": round(float(area_a), 3),
    "water_km2_b": round(float(area_b), 3),
    "change_km2": round(float(area_b - area_a), 3),
    "change_pct": round(float(100 * (area_b - area_a) / area_a), 2) if area_a else None,
    "gained_km2": round(float((change == 1).sum() * px_km2), 3),
    "lost_km2": round(float((change == -1).sum() * px_km2), 3),
}
eo.write_geotiff("change.tif", change, composites[0].grid)
eo.figure_water_change("map.png", composites[0], composites[1], a, b, "Open water at Lake Ichkeul, Tunisia: 2020-02 vs 2025-02", result)
layers = {
    "a": eo.web_layers(".", composites[0], a, prefix=f"{PERIODS[0]}_"),
    "b": eo.web_layers(".", composites[1], b, change=change, prefix=f"{PERIODS[1]}_"),
}
json.dump({"numbers": result, "layers": layers}, open("result.json", "w"), indent=2)
print(json.dumps(result, indent=2))
