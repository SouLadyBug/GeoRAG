"""NDVI at Bizerte, Tunisia, 2024-07

Generated by GeoRAG from the plan below. Method: monthly median NDVI composite from Sentinel-2
L2A (B08, B04) with the SCL cloud mask.

Plan: {"task": "ndvi", "place": "Bizerte, Tunisia", "bbox": [9.72, 37.12, 9.98, 37.32], "periods": ["2024-07"], "index": "NDVI", "threshold": 0.0, "max_cloud": 30.0, "max_scenes": 4, "resolution": 20}
"""

import json

from georag.geo import eo

BBOX = (9.72, 37.12, 9.98, 37.32)  # lon_min, lat_min, lon_max, lat_max (Bizerte, Tunisia)
MONTH = "2024-07"

comp = eo.monthly_composite(BBOX, MONTH, "NDVI", 30.0, 4, 20)
stats = eo.ndvi_stats(comp)
eo.write_geotiff(f"ndvi_{MONTH}.tif", comp.index, comp.grid, nodata=float("nan"))
result = {"place": "Bizerte, Tunisia", "bbox": BBOX, **stats}
eo.figure_index("map.png", comp, "NDVI at Bizerte, Tunisia, 2024-07")
layers = eo.web_layers(".", comp)
json.dump({"numbers": result, "layers": layers}, open("result.json", "w"), indent=2)
print(json.dumps(result, indent=2))
