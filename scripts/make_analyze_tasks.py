"""Derive the Analyze benchmark tasks (eval/bench/analyze.yaml) from JRC Global Surface Water.

For each lake, a 0.4° window around an approximate centre is read from the JRC occurrence
layer; the connected water body (occurrence ≥ 50 %) nearest the centre gives the bounding box,
padded by about 1.5 km. Each lake is asked about for two months.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import yaml
from scipy import ndimage

from georag.geo import eo

ROOT = Path(__file__).resolve().parents[1]

LAKES = [
    ("Lake Bled", 46.3633, 14.0938),
    ("Lake Bohinj", 46.2826, 13.8640),
    ("Lake Annecy", 45.8600, 6.1720),
    ("Lac du Bourget", 45.7300, 5.8700),
    ("Lake Neuchâtel", 46.9000, 6.8500),
    ("Lake Lugano", 45.9900, 9.0200),
    ("Lake Como", 46.0700, 9.2800),
    ("Lake Garda", 45.6500, 10.6700),
    ("Lake Trasimeno", 43.1300, 12.1000),
    ("Lake Bolsena", 42.6000, 11.9300),
    ("Lake Bracciano", 42.1200, 12.2300),
    ("Lake Ohrid", 41.0000, 20.7500),
    ("Lake Kinneret", 32.8200, 35.5900),
    ("Lake Doiran", 41.2100, 22.7500),
    ("Lake Ichkeul", 37.1600, 9.6600),
]
MONTHS = ["2020-08", "2024-08"]
MONTH_NAMES = {"2020-08": "August 2020", "2024-08": "August 2024"}


def lake_bbox(lat: float, lon: float, half: float = 0.2) -> tuple[tuple[float, float, float, float], float]:
    window = (lon - half, lat - half, lon + half, lat + half)
    grid = eo.analysis_grid(window, 30.0)
    occ, _ = eo.jrc_occurrence(window, grid)
    water = (occ >= 50) & (occ <= 100)
    labels, n = ndimage.label(water)
    if n == 0:
        raise RuntimeError("no water in window")
    # the component nearest the given centre
    cy, cx = grid.height // 2, grid.width // 2
    ys, xs = np.nonzero(labels)
    k = np.argmin((ys - cy) ** 2 + (xs - cx) ** 2)
    comp = labels == labels[ys[k], xs[k]]
    rows = np.where(comp.any(axis=1))[0]
    cols = np.where(comp.any(axis=0))[0]
    from pyproj import Transformer

    tr = Transformer.from_crs(grid.crs, 4326, always_xy=True)
    t = grid.transform
    pad = 50  # pixels of 30 m
    r0, r1 = max(0, rows[0] - pad), min(grid.height - 1, rows[-1] + pad)
    c0, c1 = max(0, cols[0] - pad), min(grid.width - 1, cols[-1] + pad)
    corners = [tr.transform(*(t * (c, r))) for c in (c0, c1 + 1) for r in (r0, r1 + 1)]
    lons, lats = [c[0] for c in corners], [c[1] for c in corners]
    bbox = (round(min(lons), 4), round(min(lats), 4), round(max(lons), 4), round(max(lats), 4))
    area = comp.sum() * 900 / 1e6
    return bbox, area


def main() -> None:
    tasks = []
    for name, lat, lon in LAKES:
        bbox, area = lake_bbox(lat, lon)
        span_km = (bbox[2] - bbox[0]) * 111 * math.cos(math.radians(lat))
        print(f"{name:24s} {bbox}  ~{area:.1f} km² in JRC  ({span_km:.0f} km wide)")
        for m in MONTHS:
            tasks.append(
                {
                    "id": f"{name.lower().replace(' ', '-').replace('â', 'a')}-{m}",
                    "lake": name,
                    "month": m,
                    "bbox": list(bbox),
                    "question": f"Map the open-water extent of {name} (bbox {bbox[0]}, {bbox[1]}, {bbox[2]}, {bbox[3]}) in {MONTH_NAMES[m]}.",
                }
            )
    out = ROOT / "eval" / "bench" / "analyze.yaml"
    out.write_text(
        "# Generated by scripts/make_analyze_tasks.py from JRC Global Surface Water occurrence.\n"
        + yaml.safe_dump(tasks, sort_keys=False, allow_unicode=True)
    )
    print(f"{len(tasks)} tasks → {out}")


if __name__ == "__main__":
    main()
